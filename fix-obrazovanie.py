#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Приводит формулировку об образовании к точной на всём сайте shelest-site.

Было:  «высшее медицинское образование» / «тренер с медицинским образованием»
Стало: «биологическое образование» / «биолог-эколог, НГМУ»

Факт: НГМУ 2004-2009, специальность «Биоэкология», специализация «экология
человека», квалификация биолог-эколог. Специальности «врач» на этом факультете
открылись только в 2011 году, после выпуска.

ВАЖНО: упоминания медицинских данных, медицинских ограничений и медицинской
истории КЛИЕНТА не трогаются — они корректны.

Запуск:
    cd ~/Desktop/shelest-site
    python3 fix-obrazovanie.py            # показать, что изменится (ничего не пишет)
    python3 fix-obrazovanie.py --apply    # применить
"""
import io, os, re, sys

APPLY = '--apply' in sys.argv

# Точечные замены — идут первыми, порядок важен (длинные раньше коротких)
EXACT = [
    # Шапка главной
    ("Чемпион мира · высшее медицинское образование · действующий спортсмен",
     "Чемпион мира · биолог-эколог, НГМУ · действующий спортсмен"),
    ("Чемпион мира, высшее медицинское образование, действующий спортсмен",
     "Чемпион мира, биолог-эколог (НГМУ), действующий спортсмен"),

    # Блок регалий
    ("Высшее медицинское образование", "Биолог-эколог, НГМУ"),

    # Полоска статистики и мини-приложение бота
    ("высшее медицинское образование, НГМУ", "биолог-эколог, НГМУ"),

    # Заголовки страницы онлайн-ведения
    ("Онлайн-ведение с тренером, у которого медицинское образование",
     "Онлайн-ведение с тренером, у которого профильное образование"),

    # Заголовки внешних публикаций в блоке «Публикации»
    ("Чемпион мира с медицинским образованием о креатине",
     "Чемпион мира и биолог-эколог о креатине"),
    ("Мне за 40, медицинское образование и титул чемпиона мира",
     "Мне за 40, биологическое образование и титул чемпиона мира"),
]

# Общие правила — только там, где рядом слово «образован»
GENERIC = [
    (r"с\s+высшим\s+медицинским\s+образованием",   "с биологическим образованием"),
    (r"с\s+медицинским\s+образованием",             "с биологическим образованием"),
    (r"медицинским\s+образованием",                 "биологическим образованием"),
    (r"медицинского\s+образования",                 "биологического образования"),
    (r"медицинском\s+образовании",                  "профильном образовании"),
    (r"[Вв]ысшее\s+медицинское\s+образование",      "биологическое образование"),
    (r"[Мм]едицинское\s+образование",               "биологическое образование"),
]

EXTS = ('.html', '.md', '.js')
SKIP_DIRS = {'.git', 'node_modules', '.github'}

changed_files = 0
changed_hits = 0
report = []

for root, dirs, files in os.walk('.'):
    dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
    for fn in sorted(files):
        if not fn.endswith(EXTS):
            continue
        path = os.path.join(root, fn)
        try:
            src = io.open(path, encoding='utf-8').read()
        except Exception:
            continue
        out = src

        for old, new in EXACT:
            if old in out:
                out = out.replace(old, new)
        for pat, new in GENERIC:
            out = re.sub(pat, new, out)
        # заглавная буква после точки
        out = re.sub(r'([.!?]\s+)биологическое', r'\1Биологическое', out)
        out = re.sub(r'(>\s*)биологическое', r'\1Биологическое', out)

        if out != src:
            changed_files += 1
            # посчитать и показать различия построчно
            for a, b in zip(src.splitlines(), out.splitlines()):
                if a != b:
                    changed_hits += 1
                    report.append((path, a.strip()[:110], b.strip()[:110]))
            if APPLY:
                io.open(path, 'w', encoding='utf-8').write(out)

for path, a, b in report:
    print('\n%s' % path)
    print('  было:  %s' % a)
    print('  стало: %s' % b)

print('\n' + '=' * 60)
print('Файлов затронуто: %d, строк изменено: %d' % (changed_files, changed_hits))
if APPLY:
    print('ПРИМЕНЕНО. Проверь git diff, потом коммить и пушь.')
else:
    print('Это был предпросмотр, ничего не записано.')
    print('Чтобы применить:  python3 fix-obrazovanie.py --apply')

# Напоминание про то, что скриптом не чинится
print("""
Отдельно, руками (скрипт этого не делает):
  1. Картинка визитки бота img/bot-welcome-v3.jpg — текст на изображении.
  2. Заголовок статьи на Дзене и на Пикабу.
  3. Профиль на Medium, профиль на Ответах Mail.ru.
  4. Описание канала на Дзене.
  5. Пересобрать статьи: python3 build_articles.py
""")
